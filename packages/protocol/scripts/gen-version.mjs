// Writes packages/protocol/src/version.generated.ts from the `version` field of
// packages/mcp/package.json, so MCP_PACKAGE_SPEC (and every setup command built
// from it) can never drift from the version that is actually published.
//
//   node scripts/gen-version.mjs          write the module when it differs
//   node scripts/gen-version.mjs --check  exit 1 when the module is stale
//
// `pnpm --filter @wcgw/vibe-check-protocol build` runs the writer before tsup.
// Zero dependencies (node:fs only).

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const protocolDir = join(here, '..')
const mcpPackagePath = join(protocolDir, '..', 'mcp', 'package.json')
const targetPath = join(protocolDir, 'src', 'version.generated.ts')

const SEMVER = /^\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?$/

const { version } = JSON.parse(readFileSync(mcpPackagePath, 'utf8'))
if (typeof version !== 'string' || !SEMVER.test(version)) {
  throw new Error(`packages/mcp/package.json has no valid version (got ${JSON.stringify(version)})`)
}

const expected = [
  '// GENERATED by packages/protocol/scripts/gen-version.mjs from',
  '// packages/mcp/package.json. Do not edit by hand: run',
  '// `pnpm --filter @wcgw/vibe-check-protocol build` (or `gen:version`).',
  '',
  `export const MCP_PACKAGE_VERSION = '${version}'`,
  '',
].join('\n')

let current = null
try {
  current = readFileSync(targetPath, 'utf8')
} catch {
  current = null
}

if (process.argv.includes('--check')) {
  if (current !== expected) {
    console.error(
      `src/version.generated.ts is stale: expected MCP_PACKAGE_VERSION '${version}'. `
      + 'Run `pnpm --filter @wcgw/vibe-check-protocol gen:version`.',
    )
    process.exit(1)
  }
  console.log(`version.generated.ts matches @wcgw/vibe-check-mcp@${version}`)
} else if (current !== expected) {
  writeFileSync(targetPath, expected)
  console.log(`wrote src/version.generated.ts (MCP_PACKAGE_VERSION '${version}')`)
}
